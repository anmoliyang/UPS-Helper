// Package hid 提供 UPS 的 HID 报告描述符与输入报告编码。
//
// 描述符必须逐字节对应真实 CyberPower 0764:0501 设备的 HID 布局，否则飞牛
// fnOS 自带的 NUT 驱动（usbhid-ups + cyberpower 子驱动）无法解析型号、电量等字段。
//
// 关键点：
//   - 使用多个 Report ID（0x1d/0x1f/0x03/0x20/0x21/0x22/0x23/0x28...），
//     NUT 通过这些带 ID 的 HID Feature/Input 报告读取型号、序列号、电量、电压、状态。
//   - EP1 IN 中断端点始终 NAK（无数据），所有数据经控制端点 GET_REPORT 提供。
//   - 电压/频率按 ×10 缩放（与描述符的 Unit Exponent 自洽）。
//
// 报告描述符字节流本身不涉及大小端；报告内的多字节数值按 HID 规范使用小端。
